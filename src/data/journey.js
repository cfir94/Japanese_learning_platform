// Journey sentences that practise a grammar point — for examples inside the lessons.
export function sentencesFor(pointIds) {
  const wanted = new Set(pointIds);
  return ENTRIES.flatMap((entry) => [...entry.sentences, entry.ask]
    .filter((s) => s[3]?.some((g) => wanted.has(g)))
    .map((s) => ({ entry, ja: s[0], kana: s[1], he: s[2], g: s[3] })));
}
