"""Records every Japanese text the site reads aloud, once, as a small mp3 with a natural voice.

Phones often have no Japanese voice for the browser's speech engine (Chrome on Android stays silent),
so 🔊 plays these files and falls back to the browser's voice only for text that has none (imported
lesson notes). Run on GitHub's runners (the voice service is not reachable from the build containers):

    node tools/collect_japanese.mjs > /tmp/ja.json && python3 tools/build_audio.py /tmp/ja.json

Writes assets/audio/<id>.mp3 (id = first 12 hex of sha1 of the text) and src/data/audio.js (generated).
Existing files are kept, so only new text is recorded.
"""

import asyncio
import hashlib
import json
import sys
from pathlib import Path

import edge_tts

ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "assets" / "audio"
OUT = ROOT / "src" / "data" / "audio.js"
VOICE = "ja-JP-NanamiNeural"
RATE = "-10%"


def audio_id(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:12]


def spoken(text: str) -> str:
    # "〜" marks a pattern's slot; it is not read.
    return text.replace("〜", "").strip()


async def record(text: str, gate: asyncio.Semaphore) -> bool:
    path = DIR / f"{audio_id(text)}.mp3"
    if path.exists() and path.stat().st_size > 0:
        return True
    async with gate:
        for attempt in range(3):
            try:
                await edge_tts.Communicate(spoken(text), VOICE, rate=RATE).save(str(path))
                if path.stat().st_size > 0:
                    return True
            except Exception as error:  # network hiccup: retry, then skip this one
                print(f"retry {attempt + 1} {text!r}: {error}", file=sys.stderr)
                await asyncio.sleep(2 * (attempt + 1))
        path.unlink(missing_ok=True)
        return False


async def main() -> None:
    texts = [t for t in json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))["speech"] if spoken(t)]
    DIR.mkdir(parents=True, exist_ok=True)
    gate = asyncio.Semaphore(6)
    ok = await asyncio.gather(*(record(t, gate) for t in texts))
    table = {t: audio_id(t) for t, good in zip(texts, ok) if good}
    OUT.write_text(
        "// Generated by tools/build_audio.py — do not edit. Japanese text → assets/audio/<id>.mp3\n"
        f"export const AUDIO = {json.dumps(table, ensure_ascii=False, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"{len(table)} of {len(texts)} texts have audio")
    if len(table) < len(texts) * 0.9:
        sys.exit("too many recordings failed")


asyncio.run(main())
