#!/usr/bin/env python3
"""Furigana for every Japanese text on the site.

  node tools/collect_japanese.mjs > /tmp/ja.json && python3 tools/build_furigana.py /tmp/ja.json

Readings come from pykakasi (pip install pykakasi), then tools/furigana_overrides.json fixes what
it gets wrong: {"word as written": "word with 漢字{よみ} marks"}, applied before the dictionary.
Texts with a hand-written reading (journey words and sentences) are checked against it, and every
mismatch is printed — fix it with an override, never by editing the generated file.

Writes src/data/furigana.js (generated): { text: [[base, reading], ...] }, reading '' = no ruby.
"""
import json
import re
import sys
from pathlib import Path

import pykakasi

ROOT = Path(__file__).resolve().parent.parent
OVERRIDES = json.loads((ROOT / "tools" / "furigana_overrides.json").read_text(encoding="utf-8"))
# A study kanji on its own (the week's kanji list) shows its main on・kun readings, written by hand.
KANJI_READINGS = json.loads((ROOT / "tools" / "kanji_readings.json").read_text(encoding="utf-8"))
OUT = ROOT / "src" / "data" / "furigana.js"
KANJI = re.compile(r"[㐀-鿿々]")
MARK = re.compile(r"([㐀-鿿々]+)\{([^}]+)\}")
kks = pykakasi.kakasi()


def hira(text: str) -> str:
    return "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in text)


def from_marks(annotated: str) -> list[list[str]]:
    segs, pos = [], 0
    for m in MARK.finditer(annotated):
        if m.start() > pos:
            segs.append([annotated[pos:m.start()], ""])
        segs.append([m.group(1), m.group(2)])
        pos = m.end()
    if pos < len(annotated):
        segs.append([annotated[pos:], ""])
    return segs


def split_token(orig: str, reading: str) -> list[list[str]]:
    if not KANJI.search(orig):
        return [[orig, ""]]
    pre, suf = "", ""
    while orig and reading and not KANJI.match(orig[-1]) and hira(orig[-1]) == reading[-1]:
        suf = orig[-1] + suf
        orig, reading = orig[:-1], reading[:-1]
    while orig and reading and not KANJI.match(orig[0]) and hira(orig[0]) == reading[0]:
        pre += orig[0]
        orig, reading = orig[1:], reading[1:]
    out = []
    if pre:
        out.append([pre, ""])
    out.append([orig, reading])
    if suf:
        out.append([suf, ""])
    return out


def annotate(text: str) -> list[list[str]]:
    keys = sorted((k for k in OVERRIDES if k in text), key=len, reverse=True)
    if keys:
        pattern = re.compile("(" + "|".join(map(re.escape, keys)) + ")")
        segs = []
        for piece in pattern.split(text):
            if not piece:
                continue
            segs += from_marks(OVERRIDES[piece]) if piece in OVERRIDES else annotate_plain(piece)
        return merge(segs)
    return merge(annotate_plain(text))


def annotate_plain(text: str) -> list[list[str]]:
    segs = []
    for t in kks.convert(text):
        segs += split_token(t["orig"], t["hira"])
    return segs


def merge(segs: list[list[str]]) -> list[list[str]]:
    out = []
    for base, rd in segs:
        if out and not rd and not out[-1][1]:
            out[-1][0] += base
        else:
            out.append([base, rd])
    return out


def read_all(segs) -> str:
    return "".join(rd or hira(base) for base, rd in segs)


def norm(text: str) -> str:
    return re.sub(r"[\s、。！？!?「」『』…・〜～,.\-]", "", hira(text))


def main() -> None:
    data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    table, bad = {}, []
    for text in data["texts"]:
        segs = annotate(text)
        table[text] = segs
        want = data["known"].get(text)
        if want is not None and not re.search(r"[0-9]", text) and norm(read_all(segs)) != norm(want):
            bad.append((text, read_all(segs), want))
    OUT.write_text(
        "// Generated by tools/build_furigana.py — do not edit; fix readings in tools/furigana_overrides.json.\n"
        f"export const FURIGANA = {json.dumps(table, ensure_ascii=False, separators=(',', ':'))};\n"
        "// The week's study kanji, each with its main on・kun readings (tools/kanji_readings.json).\n"
        f"export const KANJI = {json.dumps(KANJI_READINGS, ensure_ascii=False, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"{len(table)} texts; {len(bad)} differ from the hand-written readings")
    for text, got, want in bad:
        print(f"  {text}\n    got:  {got}\n    want: {want}")


if __name__ == "__main__":
    main()
